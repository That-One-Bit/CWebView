#!/usr/bin/env python3
"""Generate the CWI unit-gate fixture: a synthetic image with flat runs,
a gradient, and noisy pixels (the three RLE regimes), packed with the
REAL python codec.  The C unit decodes the file with the REAL C decoder
and must match the expected bytes exactly - cross-validating codec A
against codec B.  Also emits truncated prefixes for the fuzz loop."""
import sys, os
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "tools"))
from cwi_common import pack_cwi

W, H = 23, 7          # odd sizes on purpose: no padding assumptions
px = bytearray()
for y in range(H):
    for x in range(W):
        if x < 8:                                    # flat run regime
            r, g, b, a = 200, 40, 40, 255
        elif x < 16:                                 # gradient regime
            r, g, b, a = x * 14, y * 30, 128, 255
        else:                                        # noise regime
            r, g, b, a = (x * 37 + y * 91) & 255, (x * 11) ^ y, 90, (x * 53) & 255
        px += bytes((r, g, b, a))
px = bytes(px)
cwi = pack_cwi(px, W, H, orig_bytes=px + b"FAKE-SOURCE-FOR-ORIG-CHECK", src_name="fixture.rgba")

outdir = sys.argv[1] if len(sys.argv) > 1 else "/tmp"
with open(os.path.join(outdir, "cwi_fixture.cwi"), "wb") as f:
    f.write(cwi)
with open(os.path.join(outdir, "cwi_fixture.h"), "w") as f:
    f.write("/* generated by desktop_test/cwi_gen_fixture.py - do not edit */\n")
    f.write("#define FIX_W %d\n#define FIX_H %d\n#define FIX_LEN %d\n" % (W, H, len(cwi)))
    f.write("static const unsigned char fix_cwi[] = {\n")
    f.write(",".join(str(b) for b in cwi))
    f.write("\n};\n")
    f.write("static const unsigned char fix_px[] = {\n")
    f.write(",".join(str(b) for b in px))
    f.write("\n};\n")
    f.write("#define FIX_PX_LEN %d\n" % len(px))
print("fixture: %dx%d, cwi %d bytes, px %d bytes" % (W, H, len(cwi), len(px)))
