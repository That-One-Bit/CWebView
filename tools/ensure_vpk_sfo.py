#!/usr/bin/env python3
"""Ensure a Vita VPK contains exactly one sce_sys/param.sfo entry."""
from __future__ import annotations

import sys
import zipfile
from pathlib import Path


def main() -> int:
    if len(sys.argv) != 4:
        print("usage: ensure_vpk_sfo.py INPUT_VPK PARAM_SFO OUTPUT_VPK", file=sys.stderr)
        return 2

    input_vpk = Path(sys.argv[1])
    param_sfo = Path(sys.argv[2])
    output_vpk = Path(sys.argv[3])

    if not input_vpk.is_file():
        raise SystemExit(f"Input VPK does not exist: {input_vpk}")
    if not param_sfo.is_file():
        raise SystemExit(f"param.sfo does not exist: {param_sfo}")

    output_vpk.parent.mkdir(parents=True, exist_ok=True)
    tmp_vpk = output_vpk.with_suffix(output_vpk.suffix + ".tmp")

    with zipfile.ZipFile(input_vpk, "r") as zin:
        with zipfile.ZipFile(tmp_vpk, "w", compression=zipfile.ZIP_DEFLATED) as zout:
            found_sfo = False
            for info in zin.infolist():
                # vita-pack-vpk normally already writes this entry from -s.
                # Drop it here so the final archive has one canonical copy.
                if info.filename.rstrip("/") == "sce_sys/param.sfo":
                    if found_sfo:
                        continue
                    found_sfo = True
                    continue

                data = zin.read(info.filename)
                new_info = zipfile.ZipInfo(info.filename, info.date_time)
                new_info.compress_type = zipfile.ZIP_DEFLATED
                new_info.external_attr = info.external_attr
                new_info.comment = info.comment
                new_info.extra = info.extra
                zout.writestr(new_info, data)

            # Always write the authoritative SFO generated by VitaSDK.
            sfo_data = param_sfo.read_bytes()
            zout.writestr("sce_sys/param.sfo", sfo_data, compress_type=zipfile.ZIP_DEFLATED)

    tmp_vpk.replace(output_vpk)

    with zipfile.ZipFile(output_vpk, "r") as zf:
        count = sum(1 for name in zf.namelist() if name == "sce_sys/param.sfo")
        if count != 1:
            raise SystemExit(f"Failed to normalize sce_sys/param.sfo (found {count} copies)")

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
